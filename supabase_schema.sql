-- 1. TABEL TRANSAKSI (transactions)
CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('Pemasukan', 'Pengeluaran')),
    time TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

-- Policy agar aplikasi web bisa membaca data (SELECT) dengan Publishable Key
CREATE POLICY "Public Read transactions"
ON public.transactions
FOR SELECT
TO public
USING (true);

-- Policy agar aplikasi web bisa menambah transaksi (INSERT)
CREATE POLICY "Public Insert transactions"
ON public.transactions
FOR INSERT
TO public
WITH CHECK (true);

-- Policy agar aplikasi web bisa mengubah transaksi (UPDATE)
CREATE POLICY "Public Update transactions"
ON public.transactions
FOR UPDATE
TO public
USING (true)
WITH CHECK (true);

-- Policy agar aplikasi web bisa menghapus transaksi (DELETE)
CREATE POLICY "Public Delete transactions"
ON public.transactions
FOR DELETE
TO public
USING (true);

