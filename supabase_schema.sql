-- ========================================================
-- 2. TABEL GOALS / TARGET TABUNGAN (goals)
-- ========================================================
CREATE TABLE IF NOT EXISTS public.goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL UNIQUE,
    current NUMERIC NOT NULL DEFAULT 0,
    target NUMERIC NOT NULL DEFAULT 0,
    icon TEXT DEFAULT 'fa-bullseye',
    color TEXT DEFAULT 'emerald',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE public.goals ENABLE ROW LEVEL SECURITY;

-- Policy Read/Write Goals
CREATE POLICY "Public Read goals"
ON public.goals
FOR SELECT
TO public
USING (true);

CREATE POLICY "Public Insert goals"
ON public.goals
FOR INSERT
TO public
WITH CHECK (true);

CREATE POLICY "Public Update goals"
ON public.goals
FOR UPDATE
TO public
USING (true)
WITH CHECK (true);

CREATE POLICY "Public Delete goals"
ON public.goals
FOR DELETE
TO public
USING (true);

